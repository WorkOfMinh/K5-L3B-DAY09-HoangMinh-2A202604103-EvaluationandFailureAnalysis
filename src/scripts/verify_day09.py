"""Reproduce the individual Day9 evidence, including expected failing gates.

Run: .\.venv\Scripts\python.exe scripts/verify_day09.py (from src).
Outputs are generated by scripts; do not hand-edit reports/*.json.
"""

from __future__ import annotations

import json
import os
from pathlib import Path
import subprocess
import sys


def main() -> int:
    os.chdir(Path(__file__).resolve().parents[1])
    checks = [
        (["-m", "lab9.smoke"], 0),
        (["-m", "lab9.evalset", "--build", "--check"], 0),
        (["-m", "lab9.evalset", "--v2", "--build", "--check"], 0),
        (["-m", "pytest", "-q"], 0),
        (["-m", "pytest", "-q", "-m", "student", "-o", "addopts=", "-k", "lab9 and not advanced"], 0),
        (["-m", "pytest", "-q", "-m", "student", "-o", "addopts=", "-k", "lab9 and advanced"], 0),
        (["-m", "lab9.judge", "--csv", "data/eval/judge_tone_public.csv", "--audit", "5"], 0),
        (["-m", "lab9.judge", "--csv", "data/eval/judge_helpful_public.csv", "--audit", "5"], 1),
        (["-m", "lab9.eval", "--shape", "swarm", "--out", "reports/baseline_v1.json"], 0),
        (["-m", "lab9.eval", "--shape", "swarm", "--out", "reports/eval_pr.json"], 0),
        (["-m", "lab9.ci_check", "--pr", "reports/eval_pr.json", "--baseline", "reports/baseline_v1.json"], 0),
        (["-m", "lab9.eval", "--shape", "fixed"], 0),
        (["-m", "lab9.eval", "--shape", "seeded_regression"], 0),
        (["-m", "lab9.gate", "--pr", "reports/eval_pr.json", "--baseline", "reports/baseline_v1.json"], 0),
        (["-m", "lab9.gate", "--pr", "reports/eval_fixed.json", "--baseline", "reports/baseline_v1.json"], 0),
        (["-m", "lab9.gate", "--pr", "reports/eval_seeded_regression.json", "--baseline", "reports/baseline_v1.json"], 1),
        (["-m", "lab9.mutation", "--detect"], 0),
        (["-m", "lab9.eval", "--shape", "swarm", "--spec", "config/metric_spec_v2.yaml", "--out", "reports/baseline_v2.json"], 0),
        (["-m", "lab9.eval", "--shape", "slice_regression", "--spec", "config/metric_spec_v2.yaml", "--out", "reports/eval_slice_regression.json"], 0),
        (["-m", "lab9.mutation", "--spec", "config/metric_spec_v2.yaml", "--aa", "66,77,88,99,110"], 0),
        (["-m", "lab9.mutation", "--spec", "config/metric_spec_v2.yaml", "--baseline", "reports/baseline_v2.json"], 0),
        (["-m", "lab9.traps", "--pr", "reports/eval_slice_regression.json", "--baseline", "reports/baseline_v2.json", "--spec", "config/metric_spec_v2.yaml"], 0),
        (["scripts/day09_evidence.py"], 0),
    ]
    results = []
    for args, expected in checks:
        print(f"\npython {' '.join(args)}", flush=True)
        done = subprocess.run([sys.executable, *args], capture_output=True, text=True, encoding="utf-8",
                              env={**os.environ, "PYTHONUTF8": "1"})
        output = done.stdout + done.stderr
        print(output, end="", flush=True)
        ok = done.returncode == expected
        # Explicit verdicts distinguish expected gate rejection from a Python crash.
        if args[:2] == ["-m", "lab9.gate"] and expected == 1:
            ok &= "exit 1 — blocked:" in output and "pass_rate" in output.split("exit 1 — blocked:")[-1]
        if args[:2] == ["-m", "lab9.judge"] and expected == 1:
            ok &= "FAIL floors" in output
        results.append({"command": ["python", *args], "expected_exit": expected,
                        "actual_exit": done.returncode, "ok": ok, "output": output})
        if not ok:
            break
    Path("reports").mkdir(exist_ok=True)
    result = {"python": sys.version, "checks": results, "expected_checks": len(checks),
              "all_passed": len(results) == len(checks) and all(r["ok"] for r in results)}
    Path("reports/day09_verification.json").write_text(json.dumps(result, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"\n{sum(r['ok'] for r in results)}/{len(checks)} checks accepted (expected failures count as accepted).")
    return 0 if result["all_passed"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
